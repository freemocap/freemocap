import {readFileSync,writeFileSync} from 'node:fs';
const spec=JSON.parse(readFileSync('contracts/openapi.json','utf8'));
const assets=new Set(['recordings_stream_video','recordings_browser_video_stream','recordings_get_recording_parquet']);
const definitions=Object.fromEntries(Object.entries(spec.paths).flatMap(([path,methods])=>Object.entries(methods)
 .filter(([,operation])=>operation.operationId)
 .map(([method,operation])=>[operation.operationId,{method:method.toUpperCase(),path,asset:assets.has(operation.operationId)}])));
writeFileSync('src/generated/operations.ts','// Generated by tools/generate-operations.mjs; asset overrides trace actual response readers.\nexport const operationDefinitions = '+JSON.stringify(definitions,null,2)+' as const;\n');
